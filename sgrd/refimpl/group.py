"""The prime-order group the reference implementation works in, and Shamir
sharing over its exponent field.

The paper does not name a cryptographic suite -- Section `sec:design` states
three architectural requirements on the threshold re-encryption and leaves the
instantiation open. A reference implementation cannot leave it open, so this
module fixes one choice and says what the choice does and does not buy.

**The group.** The order-`q` subgroup of quadratic residues modulo the 2048-bit
MODP safe prime of RFC 3526, generated by `g = 4 = 2^2`. Safe prime means
`p = 2q + 1` with `q` prime, so the quadratic residues form a prime-order group
and no small-subgroup confinement is possible: membership is one exponentiation
to check, and every non-identity element generates. :func:`self_check` verifies
all of this at run time rather than asking the reader to trust the constant.

**What this is not.** It is not a performance claim. Modular exponentiation here
is CPython's `pow`, which is perhaps an order of magnitude off a tuned bignum
library and two off hardware. Section `sec:impl` reads the timings as an upper
bound for exactly that reason, and the argument it makes -- that these
operations sit off the critical path -- only gets stronger the looser the bound.

**What it is not either.** It is not a claim that this construction is the one a
deployment should use. An elliptic-curve group would be smaller and faster. The
2048-bit MODP group is chosen because it needs no dependency beyond `int`, which
keeps the artefact auditable by anyone with a Python interpreter.
"""

from __future__ import annotations

import hashlib
import secrets
from typing import Iterable, Sequence

# RFC 3526 Section 3, the 2048-bit MODP Group (id 14). This is a safe prime:
# (p - 1) / 2 is prime, which is what makes the quadratic-residue subgroup have
